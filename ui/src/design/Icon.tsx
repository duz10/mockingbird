// Hand-rolled icon set. Lucide-style geometry, sized via `size` prop,
// stroked from currentColor so it inherits theme tint automatically.
//
// Why not ship `lucide-react`? It's 100+ KB of icons we don't need
// and adds a package. We use ~15 icons; defining them inline here
// costs ~250 lines total + zero dependencies. YAGNI + DRY.

import type { SVGProps } from "react";

interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number;
}

function base({ size = 18, ...rest }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": "true" as const,
    ...rest,
  };
}

