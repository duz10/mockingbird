    #[test]
    fn near_miss_aggregates_across_entries() {
        let m = tiny_map();
        let inputs = vec![
            TagCollapseInput {
                dictation_id: "d1".into(),
                entry_idx: 0,
                actual_tags: s(&["brake-pads"]),
                acceptable_tag_sets: vec![s(&["car-repair"])],
            },
            TagCollapseInput {
                dictation_id: "d2".into(),
                entry_idx: 0,
                actual_tags: s(&["brake-pads"]),
                acceptable_tag_sets: vec![s(&["car-repair"])],
            },
        ];
        let score = score_tag_collapse(&m, &inputs);
        assert_eq!(score.correct_at_exact, 0);
        // Both miss the same way -> single near-miss row, frequency 2.
        let nm = score
            .near_miss_top
            .iter()
            .find(|n| n.actual_tag == "brake-pad" && n.expected_tag == "car-repair")
            .expect("near-miss should be present");
        assert_eq!(nm.frequency, 2);
        assert_eq!(nm.example_dictation_ids, vec!["d1", "d2"]);
    }

