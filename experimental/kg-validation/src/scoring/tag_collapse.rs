// Per-entry + per-run scoring
// â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

/// Jaccard similarity of two sets. Empty-vs-empty is defined as 1.0
/// (both "no tags expected, no tags emitted" is full agreement); this
/// matters when an answer-key entry intentionally has an empty
/// acceptable set (rare but legal).
fn jaccard(a: &BTreeSet<String>, b: &BTreeSet<String>) -> f64 {
    if a.is_empty() && b.is_empty() {
        return 1.0;
    }
    let intersect = a.intersection(b).count();
    let union = a.union(b).count();
    if union == 0 {
        return 0.0;
    }
    intersect as f64 / union as f64
}

#[derive(Debug, Clone, Serialize)]
pub struct TagCollapseEntry {
    pub dictation_id: String,
    pub entry_idx: usize,
    pub actual_raw: Vec<String>,
    pub actual_canonical: BTreeSet<String>,
    /// The acceptable set (already canonical) that produced the
    /// highest Jaccard. Empty when there were no acceptable sets.
    pub best_match_acceptable_canonical: BTreeSet<String>,
    pub best_jaccard: f64,
    pub passed_at_exact: bool,
}

#[derive(Debug, Clone, Serialize)]
pub struct NearMiss {
    /// A tag in `actual_canonical` not in `best_match_acceptable_canonical`,
    /// OR a tag in the best match not in actual. The two directions
    /// are reported jointly because both are synonym-map iteration
    /// candidates.
    pub actual_tag: String,
    pub expected_tag: String,
    pub frequency: usize,
    pub example_dictation_ids: Vec<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct TagCollapseScore {
    pub synonym_map_version: String,
    pub total_entries: usize,
    /// Numerator of the primary Â§8.4 metric (Jaccard 1.0).
    pub correct_at_exact: usize,
    /// Observational sidecars â€” count entries with `best_jaccard >= threshold`.
    pub correct_at_0_8: usize,
    pub correct_at_0_67: usize,
    pub correct_at_0_5: usize,
    pub per_entry: Vec<TagCollapseEntry>,
    /// Top-N near-miss pairs ranked by frequency; N = 10 by default.
    pub near_miss_top: Vec<NearMiss>,
}

impl TagCollapseScore {
    /// The Â§8.4 â‰¥ 80% gate operates on this ratio.
    pub fn exact_percentage(&self) -> f64 {
        if self.total_entries == 0 {
            0.0
        } else {
            100.0 * self.correct_at_exact as f64 / self.total_entries as f64
        }
    }
}

/// Input to [`score_tag_collapse`]: one element per gradable
/// (pipeline-entry, answer-key-entry) pair. Junk-bucket entries are
/// excluded by the caller â€” they don't have acceptable tag sets.
/// Owns its data so the test ergonomics stay tolerable (the runtime
/// caller is `build_inputs_from_pairs` which clones once per entry,
/// and the total entry count is ~80, so this is irrelevant for
/// performance).
#[derive(Debug, Clone)]
pub struct TagCollapseInput {
    pub dictation_id: String,
    pub entry_idx: usize,
    pub actual_tags: Vec<String>,
    pub acceptable_tag_sets: Vec<Vec<String>>,
}

pub fn score_tag_collapse(map: &SynonymMap, inputs: &[TagCollapseInput]) -> TagCollapseScore {
    let mut per_entry: Vec<TagCollapseEntry> = Vec::with_capacity(inputs.len());
    let mut correct_at_exact = 0usize;
    let mut correct_at_0_8 = 0usize;
    let mut correct_at_0_67 = 0usize;
    let mut correct_at_0_5 = 0usize;

    // Near-miss aggregation: (actual_tag, expected_tag) -> (count, [example_ids])
    let mut nm_counter: BTreeMap<(String, String), (usize, Vec<String>)> = BTreeMap::new();

    for input in inputs {
        let actual_canonical = map.canonicalize_set(&input.actual_tags);

        let (best_jaccard, best_match) = if input.acceptable_tag_sets.is_empty() {
            // No acceptable set to score against â€” neutral. We
            // exclude such entries from the denominator at the
            // caller, but defensive zero-fill here.
            (0.0, BTreeSet::<String>::new())
        } else {
            // Track the best (j, canon) pair seen so far. Initialize
            // with the first acceptable set even if Jaccard is 0 so
            // near-miss attribution always has SOMETHING to diff
            // against.
            let mut best: Option<(f64, BTreeSet<String>)> = None;
            for set in &input.acceptable_tag_sets {
                let canon = map.canonicalize_set(set);
                let j = jaccard(&actual_canonical, &canon);
                let take = match &best {
                    None => true,
                    Some((cur, _)) => j > *cur,
                };
                if take {
                    best = Some((j, canon));
                }
            }
            best.unwrap_or((0.0, BTreeSet::new()))
        };

        let passed = (best_jaccard - 1.0).abs() < f64::EPSILON;
        if passed {
            correct_at_exact += 1;
        }
        if best_jaccard + 1e-9 >= 0.8 {
            correct_at_0_8 += 1;
        }
        if best_jaccard + 1e-9 >= 0.67 {
            correct_at_0_67 += 1;
        }
        if best_jaccard + 1e-9 >= 0.5 {
            correct_at_0_5 += 1;
        }

        // Accumulate near-misses (only when not passing â€” passed
        // entries have empty symmetric difference by definition).
        if !passed {
            let only_in_actual: Vec<&String> = actual_canonical.difference(&best_match).collect();
            let only_in_expected: Vec<&String> = best_match.difference(&actual_canonical).collect();
            // Cross-product of the symmetric difference: each
            // unmatched-actual-tag paired with each unmatched-
            // expected-tag is a candidate "should have been collapsed
            // to the same canonical". The single-tag-on-one-side case
            // pairs against an empty sentinel "(missing)".
            if only_in_actual.is_empty() && !only_in_expected.is_empty() {
                for e in &only_in_expected {
                    bump_near_miss(
                        &mut nm_counter,
                        "(missing)".to_string(),
                        (*e).clone(),
                        &input.dictation_id,
                    );
                }
            } else if !only_in_actual.is_empty() && only_in_expected.is_empty() {
                for a in &only_in_actual {
                    bump_near_miss(
                        &mut nm_counter,
                        (*a).clone(),
                        "(extra)".to_string(),
                        &input.dictation_id,
                    );
                }
            } else {
                for a in &only_in_actual {
                    for e in &only_in_expected {
                        bump_near_miss(
                            &mut nm_counter,
                            (*a).clone(),
                            (*e).clone(),
                            &input.dictation_id,
                        );
                    }
                }
            }
        }

        per_entry.push(TagCollapseEntry {
            dictation_id: input.dictation_id.clone(),
            entry_idx: input.entry_idx,
            actual_raw: input.actual_tags.clone(),
            actual_canonical,
            best_match_acceptable_canonical: best_match,
            best_jaccard,
            passed_at_exact: passed,
        });
    }

    // Rank near-misses by frequency desc, then alphabetical for
    // stability. Cap at top-10.
    let mut near_miss_top: Vec<NearMiss> = nm_counter
        .into_iter()
        .map(|((a, e), (freq, ids))| NearMiss {
            actual_tag: a,
            expected_tag: e,
            frequency: freq,
            example_dictation_ids: ids,
        })
        .collect();
    near_miss_top.sort_by(|x, y| {
        y.frequency
            .cmp(&x.frequency)
            .then_with(|| x.actual_tag.cmp(&y.actual_tag))
            .then_with(|| x.expected_tag.cmp(&y.expected_tag))
    });
    near_miss_top.truncate(10);

    TagCollapseScore {
        synonym_map_version: map.version.clone(),
        total_entries: per_entry.len(),
        correct_at_exact,
        correct_at_0_8,
        correct_at_0_67,
        correct_at_0_5,
        per_entry,
        near_miss_top,
    }
}

fn bump_near_miss(
    counter: &mut BTreeMap<(String, String), (usize, Vec<String>)>,
    actual: String,
    expected: String,
    dictation_id: &str,
) {
    let entry = counter.entry((actual, expected)).or_insert((0, Vec::new()));
    entry.0 += 1;
    // Keep at most 3 example IDs to avoid runaway lists.
    if entry.1.len() < 3 && !entry.1.iter().any(|x| x == dictation_id) {
        entry.1.push(dictation_id.to_string());
    }
}

/// Convenience helper: build the inputs vector from a slice of
/// (answer-key, actual-entries) pairs. Junk dictations are skipped.
pub fn build_inputs_from_pairs(
    pairs: &[(String, AnswerKey, Vec<crate::schema::Entry>)],
) -> Vec<TagCollapseInput> {
    let mut out = Vec::new();
    for (id, key, actual) in pairs {
        if key.is_junk_no_entry_expected {
            continue;
        }
        for (idx, (expected, actual_entry)) in key.entries.iter().zip(actual.iter()).enumerate() {
            out.push(TagCollapseInput {
                dictation_id: id.clone(),
                entry_idx: idx,
                actual_tags: actual_entry.topic_tags.clone(),
                acceptable_tag_sets: expected.acceptable_topic_tag_sets.clone(),
            });
        }
    }
    out
}

