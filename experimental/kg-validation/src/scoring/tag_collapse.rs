//! Deterministic tag-collapse scoring per ADR 0048 Â§G7.
//!
//! Supersedes the LLM tag-equivalence judge for the tag-collapse
//! metric only. The judge architecture in [`crate::scoring::judge`] +
//! [`crate::scoring::judge_validation`] is preserved for any future
//! LLM-judged metric; it is not invoked here.
//!
//! ## Algorithm (per pipeline entry)
//!
//! 1. Canonicalize the entry's `topic_tags` via the synonym map.
//!    Canonicalization is (a) re-normalize via the pipeline rules
//!    in [`crate::passes::normalize`] (defends against authoring
//!    slips in the answer keys) then (b) look the result up in the
//!    synonym map's variant-to-canonical index, falling back to the
//!    input if no mapping exists.
//! 2. Canonicalize every `acceptable_topic_tag_sets[i]` from the
//!    answer key the same way.
//! 3. Compute the Jaccard similarity between the actual canonical
//!    set and each acceptable canonical set. Take the MAX.
//! 4. **Pass condition:** `MAX(jaccard) == 1.0` â€” i.e. exact set
//!    equality on at least one acceptable set after canonicalization.
//! 5. Record Jaccard at lower thresholds (0.8, 0.67, 0.5) as
//!    observational sidecars; they do not gate.
//! 6. For non-passing entries, record every `(actual_tag, expected_tag)`
//!    pair that contributed to the symmetric difference vs. the
//!    best-matching acceptable set. These feed the near-miss aggregator.
//!
//! ## Why exact match (Jaccard 1.0)?
//!
//! The synonym map IS the equivalence engine. Accepting partial
//! overlap on top of it double-counts forgiveness and obscures map
//! gaps. Misses at 1.0 point directly to synonym-map candidates for
//! the Wave 5 iteration loop â€” which is the metric's intended
//! feedback loop. ADR 0048 Â§G7 rationale.

