/// On-disk synonym map schema. Generated by
/// `experimental/kg-validation/scripts/generate-synonym-map.ps1` from
/// the answer-key vocabulary + Bernard's hand-augmented seeds +
/// diff-driven discovery. See ADR 0048 Â§G7 for the authoring
/// procedure + discipline rules.
#[derive(Debug, Clone, Deserialize)]
pub struct SynonymMapFile {
    pub version: String,
    pub schema_version: String,
    #[serde(default)]
    pub generated_from: Vec<String>,
    #[serde(default)]
    pub discipline_notes: String,
    pub synonyms: Vec<SynonymEntry>,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct SynonymEntry {
    pub canonical: String,
    pub variants: Vec<String>,
    #[serde(default)]
    pub rationale: String,
    pub source: String,
}

/// Loaded synonym map. The variant index is a flat lookup table:
/// every variant -> its canonical. Canonicals self-map (so a tag
/// already in canonical form survives unchanged). Unknown tags pass
/// through identity at canonicalization time.
#[derive(Debug, Clone)]
pub struct SynonymMap {
    pub version: String,
    pub schema_version: String,
    /// variant (or canonical) -> canonical
    pub variant_to_canonical: BTreeMap<String, String>,
}

impl SynonymMap {
    pub fn load(path: &Path) -> anyhow::Result<Self> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| anyhow::anyhow!("read {}: {e}", path.display()))?;
        let file: SynonymMapFile = serde_json::from_str(&text)
            .map_err(|e| anyhow::anyhow!("parse {}: {e}", path.display()))?;
        if file.schema_version != "synonym-map-v1" {
            anyhow::bail!(
                "synonym-map schema_version mismatch: got {:?}, want synonym-map-v1",
                file.schema_version
            );
        }
        let mut idx: BTreeMap<String, String> = BTreeMap::new();
        for e in &file.synonyms {
            // Canonical self-maps.
            idx.insert(e.canonical.clone(), e.canonical.clone());
            for v in &e.variants {
                // Detect collisions: a variant mapped to two different
                // canonicals is an authoring bug â€” caller should fix
                // the JSON, not silently lose data.
                if let Some(existing) = idx.get(v) {
                    if existing != &e.canonical {
                        anyhow::bail!(
                            "synonym-map collision: variant {:?} maps to both {:?} and {:?}",
                            v,
                            existing,
                            e.canonical
                        );
                    }
                }
                idx.insert(v.clone(), e.canonical.clone());
            }
        }
        Ok(Self {
            version: file.version,
            schema_version: file.schema_version,
            variant_to_canonical: idx,
        })
    }

    /// Canonicalize a single tag. Re-normalizes via the pipeline
    /// rules first (defensive against authoring slips), then maps
    /// via the synonym index. Unknown tags pass through their
    /// normalized form unchanged.
    pub fn canonicalize(&self, tag: &str) -> String {
        let normalized = normalize_tags(&[tag.to_string()])
            .into_iter()
            .next()
            .unwrap_or_default();
        if normalized.is_empty() {
            return normalized;
        }
        self.variant_to_canonical
            .get(&normalized)
            .cloned()
            .unwrap_or(normalized)
    }

    /// Canonicalize a whole set of tags. Set semantics â€” duplicates
    /// after canonicalization collapse, order is irrelevant.
    pub fn canonicalize_set(&self, tags: &[String]) -> BTreeSet<String> {
        tags.iter()
            .map(|t| self.canonicalize(t))
            .filter(|t| !t.is_empty())
            .collect()
    }
}

